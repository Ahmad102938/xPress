#!/usr/bin/env bash
# Writes apps/web/.env.test.local for the auth e2e suite from the LOCAL Supabase stack
# (docs/specs/auth.md R1-M19, R2-B2, R2-N11). Never points at a remote project. The file is
# git-ignored and its values are never printed.
set -euo pipefail

web_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
root_dir="$(cd "$web_dir/../.." && pwd)"
out="$web_dir/.env.test.local"

status="$(cd "$root_dir" && pnpm -s exec supabase status -o env 2>/dev/null)"
value() { printf '%s\n' "$status" | sed -n "s/^$1=//p" | head -1 | sed -e 's/^"//' -e 's/"$//'; }

api_url="$(value API_URL)"
anon_key="$(value ANON_KEY)"
service_key="$(value SERVICE_ROLE_KEY)"
mailpit_url="$(value MAILPIT_URL)"
if [[ -z "$api_url" || -z "$anon_key" || -z "$service_key" ]]; then
  echo "Local Supabase is not running. Start it with: pnpm db:start" >&2
  exit 1
fi
case "$api_url" in
  http://127.0.0.1:*|http://localhost:*) ;;
  *) echo "Refusing: API_URL is not local." >&2; exit 1 ;;
esac

umask 077
cat > "$out" <<ENV
# Generated by scripts/auth-e2e-env.sh from the LOCAL Supabase stack. Do not commit.
NEXT_PUBLIC_SUPABASE_URL=$api_url
NEXT_PUBLIC_SUPABASE_ANON_KEY=$anon_key
SUPABASE_SERVICE_ROLE_KEY=$service_key
MAILPIT_URL=${mailpit_url:-http://127.0.0.1:54324}
NEXT_PUBLIC_SITE_URL=http://localhost:3200
AUTH_METHODS=phone,email,google
RATE_LIMIT_HMAC_SECRET=local-e2e-only-not-a-secret
CRON_SECRET=local-e2e-only-not-a-secret
ENV
echo "Wrote apps/web/.env.test.local (local stack)."
